"""Package small auditable measurements, manifests and charts; never copy datasets."""
import argparse
import json
from pathlib import Path
import shutil
from bda.batch.benchmark import records
from bda.batch.plot import render


def publish(campaign, output):
    campaign, output = Path(campaign),Path(output)
    output.mkdir(parents=True,exist_ok=False)
    experiments = json.loads((campaign/'campaign.json').read_text())
    shutil.copyfile(campaign/'campaign.json',output/'campaign.json')
    trials, environments, tasks, journals = [],{}, {},[]
    issues = []
    for experiment in experiments:
        label = experiment['label']
        root = campaign/label
        journal = root/'trials.jsonl'
        if experiment['exit_code'] != 0:
            issues.append(dict(label=label,status='failed_experiment',exit_code=experiment['exit_code']))
        if journal.exists():
            journals.append(journal)
            rows = [dict(row,experiment=label) for row in records(journal)]
            trials.extend(rows)
            issues.extend(row for row in rows if row.get('status')!='success')
            destination = output/'journals'
            destination.mkdir(exist_ok=True)
            shutil.copyfile(journal,destination/f'{label}.jsonl')
        else:
            issues.append(dict(label=label,status='missing_journal'))
        for name, bucket in [('environment.json',environments),('task-metrics.json',tasks)]:
            if (root/name).exists():
                bucket[label] = json.loads((root/name).read_text())
    for name,value in [('trials.json',trials),('environments.json',environments),('task-metrics.json',tasks),('issues.json',issues)]:
        (output/name).write_text(json.dumps(value,sort_keys=True,indent=2)+'\n')
    datasets = {}
    storage = {}
    for name in ('raw-100k','raw-1m','raw-5m'):
        path = campaign.parent/name/'manifest.json'
        if path.exists():
            datasets[name] = json.loads(path.read_text())
    for experiment in experiments:
        command = experiment['command']
        if '--storage-manifest' in command:
            reference = Path(command[command.index('--storage-manifest')+1])
            # The runner maps /artifacts to campaign.parent; preserve only size/provenance metadata.
            path = campaign.parent.joinpath(*reference.parts[2:])
            data = json.loads(path.read_text())
            storage[path.parent.name] = {k:data.get(k) for k in ('dataset_id','validated_count','validated_bytes','output_bytes','build_seconds','validation_write_seconds','validated_output_bytes_per_second')}
    (output/'datasets.json').write_text(json.dumps(datasets,sort_keys=True,indent=2)+'\n')
    (output/'storage.json').write_text(json.dumps(storage,sort_keys=True,indent=2)+'\n')
    candidates = [r for r in trials if r.get('engine')=='spark' and r.get('status')=='success' and not r.get('warmup') and r.get('record_count')==1000000]
    if candidates:
        row = candidates[0]
        shutil.copyfile(campaign/row['experiment']/f"{row['run_id']}.json",output/'sample-aggregates-1m.json')
    render(journals,output/'charts')
    (output/'README.md').write_text(
        '# Phase 3 measured evidence\n\n'
        'Generated by `python -m bda.batch.publish`. Datasets are not included.\n'
        'trials.json contains warmups and every measured outcome; journals preserve original starts/results.\n'
        'issues.json lists failures/incomplete records without replacing them.\n'
        'datasets.json records generator inputs/checksums/expected statistics; environments.json and task-metrics.json capture runtime evidence.\n'
        'Charts show measured medians and observed min/max, not confidence intervals.\n'
        'See ../../PHASE3_VALIDATION.md for exact commands, limitations and interpretation.\n')
    if issues:
        raise RuntimeError('report retains failed/incomplete experiments; consult issues.json')
    return len(trials)


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--campaign',required=True)
    p.add_argument('--output',required=True)
    args = p.parse_args()
    print(publish(args.campaign,args.output))
